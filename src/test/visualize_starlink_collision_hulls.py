"""Render the exact convex collision meshes generated for a URDF.

The left object is the original base_star_link visual STL.  The right object is
rebuilt from ``RigidGeom.mesh`` objects after Genesis has performed decimation
and convex decomposition.  Rebuilding the collision meshes as visual-only
entities avoids relying on the renderer's ``vis_mode='collision'`` path.
"""

from __future__ import annotations

import argparse
import math
from datetime import datetime
from pathlib import Path

import numpy as np
import torch

import genesis as gs


THIS_DIR = Path(__file__).resolve().parent
SRC_DIR = THIS_DIR.parent
STARLINK_URDF = SRC_DIR / "assets" / "urdf" / "starlink" / "urdf" / "starlink.urdf"
STARLINK_BASE_STL = SRC_DIR / "assets" / "urdf" / "starlink" / "meshes" / "base_star_link.STL"
DEFAULT_OUTPUT_DIR = SRC_DIR / "recordings" / "collision_hull_debug"
DEFAULT_SCALE = 0.7

COLORS = (
    (0.95, 0.20, 0.16),
    (0.10, 0.72, 0.32),
    (0.10, 0.45, 0.95),
    (0.98, 0.65, 0.08),
    (0.72, 0.22, 0.90),
    (0.00, 0.72, 0.76),
)


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Compare a URDF's visual geometry with the exact convex collision "
            "meshes generated by Genesis."
        )
    )
    parser.add_argument(
        "--urdf",
        type=Path,
        default=STARLINK_URDF,
        help="URDF to inspect. Defaults to the project's Starlink target.",
    )
    parser.add_argument(
        "--scale",
        type=float,
        default=DEFAULT_SCALE,
        help="Uniform Genesis URDF scale. Defaults to the Starlink scene scale, 0.7.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Output root. Each invocation creates a unique run_TIMESTAMP subdirectory.",
    )
    parser.add_argument("--res", default="1280x720", help="Video resolution, e.g. 1280x720.")
    parser.add_argument("--frames", type=int, default=240)
    parser.add_argument("--fps", type=int, default=60)
    parser.add_argument("--no-viewer", action="store_true")
    parser.add_argument(
        "--renderer",
        choices=("software", "genesis"),
        default="software",
        help=(
            "'software' is headless and robust; 'genesis' uses the Genesis "
            "camera/viewer. Both render the same exported RigidGeom meshes."
        ),
    )
    parser.add_argument(
        "--all-geoms",
        action="store_true",
        help="Also render the solar-panel collision hull. Default focuses on the base and its holes.",
    )
    parser.add_argument(
        "--backend",
        choices=("auto", "cpu", "gpu"),
        default="auto",
    )
    return parser.parse_args()


def parse_resolution(value: str) -> tuple[int, int]:
    fields = value.lower().replace(",", "x").split("x")
    if len(fields) != 2:
        raise ValueError(f"Invalid resolution {value!r}; expected WIDTHxHEIGHT.")
    return int(fields[0]), int(fields[1])


def choose_backend(name: str):
    if name == "cpu":
        return gs.cpu
    if name == "gpu":
        return gs.gpu
    return gs.gpu if torch.cuda.is_available() else gs.cpu


def create_unique_run_dir(output_root: Path) -> Path:
    output_root.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    candidate = output_root / f"run_{timestamp}"
    suffix = 1
    while candidate.exists():
        candidate = output_root / f"run_{timestamp}_{suffix:02d}"
        suffix += 1
    candidate.mkdir(parents=False, exist_ok=False)
    return candidate


def transformed_geom_mesh(geom, link_transform, mesh_attribute="mesh"):
    """Return a geom mesh transformed into the URDF model frame."""
    mesh = getattr(geom, mesh_attribute).trimesh.copy()
    geom_transform = gs.utils.geom.trans_quat_to_T(geom.init_pos, geom.init_quat)
    transform = link_transform @ geom_transform
    mesh.apply_transform(transform)
    return mesh


def collect_entity_meshes(entity, geom_attribute, mesh_attribute):
    """Collect all link geoms in the neutral URDF pose."""
    link_transforms = {}
    meshes = []
    for link in entity.links:
        if link.parent_idx < entity.link_start:
            # Ignore the diagnostic entity's world offset; use the URDF model frame.
            link_transform = np.eye(4)
        else:
            parent_transform = link_transforms[link.parent_idx]
            link_local = gs.utils.geom.trans_quat_to_T(link.pos, link.quat)
            link_transform = parent_transform @ link_local
        link_transforms[link.idx] = link_transform

        for geom in getattr(link, geom_attribute):
            meshes.append(transformed_geom_mesh(geom, link_transform, mesh_attribute))
    return meshes


def find_starlink_hole_centers(scale):
    """Find the three small cylindrical void axes from a horizontal STL slice."""
    import trimesh

    raw = trimesh.load_mesh(STARLINK_BASE_STL, process=True)
    section_z = min(0.33, float(raw.bounds[1, 2]) - 1.0e-3)
    section = raw.section(
        plane_origin=(0.0, 0.0, section_z),
        plane_normal=(0.0, 0.0, 1.0),
    )
    if section is None:
        return []

    candidates = []
    for loop in section.discrete:
        perimeter = float(np.linalg.norm(np.diff(loop, axis=0), axis=1).sum())
        # At this section the outer cylinder loops are about 0.626 m and the
        # inner loops are about 0.501 m. Keep one outer loop per tube.
        if 0.58 < perimeter < 0.70:
            center = np.asarray(loop, dtype=np.float64).mean(axis=0)
            center[2] = section_z
            candidates.append(center * scale)
    return candidates


def point_inside_convex_mesh(point, mesh, tolerance=1.0e-7):
    from scipy.spatial import ConvexHull

    hull = ConvexHull(np.asarray(mesh.vertices))
    signed = hull.equations[:, :3] @ np.asarray(point) + hull.equations[:, 3]
    return bool(np.max(signed) <= tolerance)


def write_report(path: Path, urdf_path, scale, all_meshes, displayed_indices, hole_centers):
    lines = [
        "Starlink Genesis collision geometry report",
        f"URDF: {urdf_path}",
        f"scale: {scale}",
        f"generated collision geom count: {len(all_meshes)}",
        f"displayed collision geom indices: {displayed_indices}",
        "",
    ]
    for idx, mesh in enumerate(all_meshes):
        bounds = np.asarray(mesh.bounds)
        lines.append(
            f"geom {idx}: vertices={len(mesh.vertices)} faces={len(mesh.faces)} "
            f"convex={mesh.is_convex} bounds={np.round(bounds, 6).tolist()}"
        )

    lines.extend(("", "Hole-center containment test:"))
    for hole_idx, point in enumerate(hole_centers):
        containing = [
            idx
            for idx, mesh in enumerate(all_meshes)
            if point_inside_convex_mesh(point, mesh)
        ]
        lines.append(
            f"hole {hole_idx}: point={np.round(point, 6).tolist()} "
            f"inside_collision_geoms={containing}"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def save_image(path: Path, rgb):
    from PIL import Image

    image = np.asarray(rgb)
    if image.ndim == 4:
        image = image[0]
    if image.dtype != np.uint8:
        if np.issubdtype(image.dtype, np.floating) and image.max(initial=0.0) <= 1.0:
            image = image * 255.0
        image = np.clip(image, 0, 255).astype(np.uint8)
    Image.fromarray(image[..., :3]).save(path)


def configure_axes(ax, all_points, title):
    lower = all_points.min(axis=0)
    upper = all_points.max(axis=0)
    center = 0.5 * (lower + upper)
    radius = 0.55 * float(np.max(upper - lower))
    ax.set_xlim(center[0] - radius, center[0] + radius)
    ax.set_ylim(center[1] - radius, center[1] + radius)
    ax.set_zlim(center[2] - radius * 0.55, center[2] + radius * 0.55)
    ax.set_box_aspect((1.0, 1.0, 0.55))
    ax.set_facecolor((0.025, 0.03, 0.04))
    ax.set_title(title, color="white", fontsize=11)
    ax.set_axis_off()


def add_mesh_to_axes(ax, mesh, color, alpha=1.0):
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection

    triangles = np.asarray(mesh.vertices)[np.asarray(mesh.faces)]
    collection = Poly3DCollection(
        triangles,
        facecolor=(*color, alpha),
        edgecolor=(*color, min(1.0, alpha + 0.15)),
        linewidth=0.08,
    )
    ax.add_collection3d(collection)


def render_with_software(
    image_path: Path,
    video_path: Path,
    visual_mesh,
    collision_meshes,
    width: int,
    height: int,
    frames: int,
    fps: int,
):
    """Render exact meshes without requiring an EGL/OpenGL context."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import imageio.v2 as imageio

    dpi = 100
    fig = plt.figure(figsize=(width / dpi, height / dpi), dpi=dpi, facecolor=(0.025, 0.03, 0.04))
    left = fig.add_subplot(1, 2, 1, projection="3d")
    right = fig.add_subplot(1, 2, 2, projection="3d")
    fig.subplots_adjust(left=0.01, right=0.99, bottom=0.01, top=0.91, wspace=0.02)

    add_mesh_to_axes(left, visual_mesh, (0.72, 0.78, 0.86))
    for color_idx, mesh in enumerate(collision_meshes):
        add_mesh_to_axes(right, mesh, COLORS[color_idx % len(COLORS)])

    visual_points = np.asarray(visual_mesh.vertices)
    collision_points = np.concatenate([np.asarray(mesh.vertices) for mesh in collision_meshes], axis=0)
    configure_axes(left, visual_points, "Original visual STL")
    configure_axes(right, collision_points, "Exact Genesis collision hulls")

    writer = imageio.get_writer(video_path, fps=max(1, fps), codec="libx264", quality=8)
    first_frame = None
    try:
        for frame_idx in range(max(1, frames)):
            azimuth = 25.0 + 360.0 * frame_idx / max(1, frames)
            left.view_init(elev=52.0, azim=azimuth)
            right.view_init(elev=52.0, azim=azimuth)
            fig.canvas.draw()
            rgba = np.asarray(fig.canvas.buffer_rgba())
            rgb = np.ascontiguousarray(rgba[..., :3])
            if first_frame is None:
                first_frame = rgb.copy()
            writer.append_data(rgb)
    finally:
        writer.close()
        plt.close(fig)

    save_image(image_path, first_frame)


def main():
    args = parse_args()
    urdf_path = args.urdf.expanduser().resolve()
    if not urdf_path.is_file():
        raise FileNotFoundError(f"URDF does not exist: {urdf_path}")
    if args.scale <= 0.0:
        raise ValueError(f"--scale must be positive; got {args.scale}.")

    width, height = parse_resolution(args.res)
    run_dir = create_unique_run_dir(args.output_dir)
    generated_dir = run_dir / "generated_collision_meshes"
    generated_dir.mkdir(parents=True, exist_ok=True)

    gs.init(
        backend=choose_backend(args.backend),
        precision="32",
        logging_level="info",
        seed=0,
    )
    scene = gs.Scene(
        sim_options=gs.options.SimOptions(dt=0.01, substeps=1),
        rigid_options=gs.options.RigidOptions(gravity=(0.0, 0.0, 0.0)),
        viewer_options=gs.options.ViewerOptions(
            camera_pos=(4.8, -6.8, 3.8),
            camera_lookat=(0.0, 0.0, 0.15),
            camera_fov=38,
        ),
        vis_options=gs.options.VisOptions(
            background_color=(0.025, 0.03, 0.04),
            ambient_light=(0.55, 0.55, 0.55),
            shadow=False,
            show_world_frame=False,
        ),
        show_viewer=not args.no_viewer,
        show_FPS=False,
    )

    # This entity runs the exact same default URDF collision processing as the
    # project target. It is hidden far below the diagnostic objects.
    source = scene.add_entity(
        morph=gs.morphs.URDF(
            file=str(urdf_path),
            pos=(0.0, 0.0, -100.0),
            scale=args.scale,
            fixed=True,
            visualization=True,
            collision=True,
        ),
        material=gs.materials.Rigid(gravity_compensation=1.0),
        name="collision_source_hidden",
    )

    all_meshes = collect_entity_meshes(source, "geoms", "mesh")
    if not all_meshes:
        raise RuntimeError(f"Genesis generated no collision geometries for {urdf_path}.")

    visual_meshes = collect_entity_meshes(source, "vgeoms", "vmesh")
    if not visual_meshes:
        raise RuntimeError(f"Genesis parsed no visual geometries from {urdf_path}.")

    # With fixed-link merging, the panel hull is the long, thin geom. Exclude it
    # in the default close-up while retaining every base collision hull exactly.
    is_default_starlink = urdf_path == STARLINK_URDF.resolve()
    base_indices = (
        [
            idx
            for idx, mesh in enumerate(all_meshes)
            if float(np.asarray(mesh.extents)[2]) > 0.20 * args.scale / DEFAULT_SCALE
        ]
        if is_default_starlink
        else list(range(len(all_meshes)))
    )
    displayed_indices = list(range(len(all_meshes))) if args.all_geoms else base_indices
    if not displayed_indices:
        displayed_indices = list(range(len(all_meshes)))

    visual_offset = np.array((0.0, -1.55, 0.0))
    collision_offset = np.array((0.0, 1.55, 0.0))

    visual_export_paths = []
    for visual_idx, visual_mesh in enumerate(visual_meshes):
        export_path = generated_dir / f"visual_geom_{visual_idx:02d}.stl"
        visual_mesh.export(export_path)
        visual_export_paths.append(export_path)
        scene.add_entity(
            morph=gs.morphs.Mesh(
                file=str(export_path),
                pos=tuple(visual_offset),
                fixed=True,
                collision=False,
                visualization=True,
                decimate=False,
                convexify=False,
            ),
            material=gs.materials.Rigid(gravity_compensation=1.0),
            surface=gs.surfaces.Rough(color=(0.72, 0.78, 0.86), smooth=False),
            name=f"rendered_visual_geom_{visual_idx}",
        )

    for color_idx, geom_idx in enumerate(displayed_indices):
        export_path = generated_dir / f"collision_geom_{geom_idx:02d}.stl"
        all_meshes[geom_idx].export(export_path)
        scene.add_entity(
            morph=gs.morphs.Mesh(
                file=str(export_path),
                pos=tuple(collision_offset),
                fixed=True,
                collision=False,
                visualization=True,
                decimate=False,
                convexify=False,
            ),
            material=gs.materials.Rigid(gravity_compensation=1.0),
            surface=gs.surfaces.Rough(
                color=COLORS[color_idx % len(COLORS)],
                smooth=False,
            ),
            name=f"rendered_collision_geom_{geom_idx}",
        )

    hole_centers = find_starlink_hole_centers(args.scale) if is_default_starlink else []
    report_path = run_dir / "collision_geometry_report.txt"
    write_report(
        report_path,
        urdf_path,
        args.scale,
        all_meshes,
        displayed_indices,
        hole_centers,
    )

    image_path = run_dir / "urdf_visual_vs_collision.png"
    video_path = run_dir / "urdf_visual_vs_collision.mp4"
    frames = max(1, int(args.frames))
    if args.renderer == "software":
        import trimesh

        visual_mesh = trimesh.util.concatenate(visual_meshes)
        render_with_software(
            image_path=image_path,
            video_path=video_path,
            visual_mesh=visual_mesh,
            collision_meshes=[all_meshes[idx] for idx in displayed_indices],
            width=width,
            height=height,
            frames=frames,
            fps=max(1, int(args.fps)),
        )
    else:
        camera = scene.add_camera(
            res=(width, height),
            pos=(4.8, -6.8, 3.8),
            lookat=(0.0, 0.0, 0.15),
            fov=38,
            GUI=False,
            debug=True,
        )
        scene.build()
        rgb, *_ = camera.render(rgb=True, force_render=True)
        save_image(image_path, rgb)

        camera.start_recording()
        lookat = np.array((0.0, 0.0, 0.15))
        for frame_idx in range(frames):
            angle = 2.0 * math.pi * frame_idx / frames
            radius = 6.4
            camera.set_pose(
                pos=(
                    float(lookat[0] + radius * math.cos(angle)),
                    float(lookat[1] + radius * math.sin(angle)),
                    3.7,
                ),
                lookat=tuple(lookat),
            )
            scene.step()
            camera.render(rgb=True, force_render=True)
        camera.stop_recording(save_to_filename=str(video_path), fps=max(1, int(args.fps)))

    print("\n[COLLISION_HULL_DEBUG] Left: original visual STL")
    print("[COLLISION_HULL_DEBUG] Right: exact Genesis collision meshes")
    print(f"[COLLISION_HULL_DEBUG] URDF: {urdf_path}")
    print(f"[COLLISION_HULL_DEBUG] Displayed geom indices: {displayed_indices}")
    print(f"[COLLISION_HULL_DEBUG] Run directory: {run_dir}")
    print(f"[COLLISION_HULL_DEBUG] Screenshot: {image_path}")
    print(f"[COLLISION_HULL_DEBUG] Video: {video_path}")
    print(f"[COLLISION_HULL_DEBUG] Geometry report: {report_path}")


if __name__ == "__main__":
    main()
